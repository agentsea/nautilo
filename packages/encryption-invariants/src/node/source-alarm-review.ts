const LOCATOR_PATTERN =
  /^(?<path>[^#]+)#(?<kind>[a-z_]+):(?<signature>[0-9a-f]{16}):(?<occurrence>[1-9][0-9]*)$/u;

const KINDS = new Set<SourceAlarmKind>([
  "filesystem_write",
  "network_processor",
  "subprocess_processor",
  "log_emitter",
  "notification_emitter",
  "temporary_storage",
  "backup_export",
]);

const SURFACES_BY_KIND: Readonly<
  Record<SourceAlarmKind, readonly CoverageSurface[]>
> = {
  filesystem_write: ["file"],
  network_processor: ["processor"],
  subprocess_processor: ["processor"],
  log_emitter: ["log"],
  notification_emitter: ["notification"],
  temporary_storage: ["cache"],
  backup_export: ["backup", "export"],
};

const KIND_REVIEW_MARKERS: Readonly<Record<SourceAlarmKind, string>> = {
  filesystem_write: "filesystem-write alarm",
  network_processor: "network-processor alarm",
  subprocess_processor: "subprocess-processor alarm",
  log_emitter: "log-emitter alarm",
  notification_emitter: "notification-emitter alarm",
  temporary_storage: "temporary-storage alarm",
  backup_export: "backup/export alarm",
};

const DEBT_ID_PATTERN =
  /^debt\.source-alarm\.(?:db|file|wire|cache|processor|log|notification|backup|export)\.(?:filesystem_write|network_processor|subprocess_processor|log_emitter|notification_emitter|temporary_storage|backup_export)\.[0-9a-f]{16}$/u;

function locatorKind(locator: string): SourceAlarmKind | undefined {
  const match = LOCATOR_PATTERN.exec(locator);
  if (!match) return undefined;
  const kind = match.groups!["kind"] as SourceAlarmKind;
  return KINDS.has(kind) ? kind : undefined;
}

function locatorOwner(locator: string): string | undefined {
  const match = LOCATOR_PATTERN.exec(locator);
  if (!match) return undefined;
  const segments = match.groups!["path"]!.split("/");
  return segments && segments.length >= 2
    ? `${segments[0]}/${segments[1]}`
    : undefined;
}

function isValidLocator(locator: string): boolean {
  return locatorKind(locator) !== undefined
    && locatorOwner(locator) !== undefined;
}

export function sourceAlarmDebtId(
  locator: string,
  surface: CoverageSurface,
): string {
  const kind = locatorKind(locator);
  const digest = createHash("sha256").update(locator).digest("hex").slice(0, 16);
  return `debt.source-alarm.${surface}.${kind ?? "invalid"}.${digest}`;
}

function isDescriptive(value: string): boolean {
  return value.trim().length >= 12;
}

function validateReview(review: SourceAlarmReview): readonly string[] {
  const errors: string[] = [];
  if (!isValidLocator(review.locator)) {
    errors.push(`invalid source alarm review locator: ${review.locator}`);
  }
  if (review.owner.trim().length === 0) {
    errors.push(`source alarm review has no owner: ${review.locator}`);
  }
  if (!isDescriptive(review.reason)) {
    errors.push(`source alarm review has no descriptive reason: ${review.locator}`);
  }
  switch (review.closure) {
    case "declaration":
      if (review.declarationId.trim().length === 0) {
        errors.push(`source alarm declaration closure has no ID: ${review.locator}`);
      }
      break;
    case "baseline_debt":
      {
        const kind = locatorKind(review.locator);
        const expectedOwner = locatorOwner(review.locator);
        if (!DEBT_ID_PATTERN.test(review.debtId)) {
          errors.push(`source alarm debt has invalid ID: ${review.locator}`);
        }
        if (
          review.debtId !== sourceAlarmDebtId(review.locator, review.surface)
        ) {
          errors.push(
            `source alarm debt ID does not match locator and surface: ${review.locator}`,
          );
        }
        if (
          kind !== undefined
          && !SURFACES_BY_KIND[kind].includes(review.surface)
        ) {
          errors.push(
            `source alarm debt surface ${review.surface} is invalid for ${kind}: ${review.locator}`,
          );
        }
        if (
          expectedOwner !== undefined
          && review.owner.trim().length > 0
          && review.owner !== expectedOwner
        ) {
          errors.push(
            `source alarm debt owner ${review.owner} does not match locator owner ${expectedOwner}: ${review.locator}`,
          );
        }
        if (!review.reason.includes(review.locator)) {
          errors.push(
            `source alarm debt reason is not locator-specific: ${review.locator}`,
          );
        }
        if (
          kind !== undefined
          && !review.reason.includes(KIND_REVIEW_MARKERS[kind])
        ) {
          errors.push(
            `source alarm debt reason is not kind-specific: ${review.locator}`,
          );
        }
        if (
          kind !== undefined
          && !review.evidenceGap.includes(KIND_REVIEW_MARKERS[kind])
        ) {
          errors.push(
            `source alarm debt evidence gap is not kind-specific: ${review.locator}`,
          );
        }
      }
      if (!REMEDIATION_STATES.includes(review.remediationState)) {
        errors.push(`source alarm debt has invalid remediation state: ${review.locator}`);
      }
      if (!RELEASE_IMPACTS.includes(review.releaseImpact)) {
        errors.push(`source alarm debt has invalid release impact: ${review.locator}`);
      }
      if (!isDescriptive(review.evidenceGap)) {
        errors.push(`source alarm debt has no descriptive evidence gap: ${review.locator}`);
      }
      if (!review.evidenceGap.includes(review.locator)) {
        errors.push(`source alarm debt evidence gap is not locator-specific: ${review.locator}`);
      }
      break;
    case "reviewed_exclusion":
      if (review.exclusionId.trim().length === 0) {
        errors.push(`source alarm exclusion closure has no ID: ${review.locator}`);
      }
      break;
  }
  return errors;
}

/**
 * Close the deliberately broad source scanner against an exact reviewed
 * manifest. Alarm debt is separate from semantic registry debt: a mechanical
 * call-site alarm is not automatically a distinct persisted-data surface.
 */
export function inspectSourceAlarmReviews(
  alarms: readonly SourceAlarm[],
  manifestReviews: readonly SourceAlarmReview[] = CURRENT_SOURCE_ALARM_REVIEWS,
): SourceAlarmReviewInspection {
  const errors: string[] = [];
  const validManifest = new Map<string, SourceAlarmReview>();
  const seenManifest = new Set<string>();
  const seenClosureIds = new Set<string>();

  for (const review of manifestReviews) {
    if (seenManifest.has(review.locator)) {
      errors.push(`duplicate source alarm review locator: ${review.locator}`);
      continue;
    }
    seenManifest.add(review.locator);
    const closureId = review.closure === "baseline_debt"
      ? review.debtId
      : review.closure === "declaration"
      ? review.declarationId
      : review.exclusionId;
    if (closureId.trim().length > 0) {
      if (seenClosureIds.has(closureId)) {
        errors.push(`duplicate source alarm closure id: ${closureId}`);
      }
      seenClosureIds.add(closureId);
    }
    const reviewErrors = validateReview(review);
    if (reviewErrors.length > 0) {
      errors.push(...reviewErrors);
      continue;
    }
    validManifest.set(review.locator, review);
  }

  const observed = new Map(alarms.map((alarm) => [alarm.locator, alarm]));
  for (const alarm of observed.values()) {
    const kind = locatorKind(alarm.locator);
    if (kind !== undefined && alarm.kind !== kind) {
      errors.push(
        `source alarm observation kind ${alarm.kind} does not match ${kind}: ${alarm.locator}`,
      );
    }
  }
  const unmapped = [...observed.keys()]
    .filter((locator) => !validManifest.has(locator));
  const stale = [...validManifest.keys()]
    .filter((locator) => !observed.has(locator));
  for (const locator of unmapped) {
    errors.push(`new source alarm has no closure: ${locator}`);
  }
  for (const locator of stale) {
    errors.push(`stale source alarm review: ${locator}`);
  }

  const reviews: SourceAlarmReview[] = [...observed.values()]
    .flatMap((alarm) => {
      const review = validManifest.get(alarm.locator);
      return review ? [review] : [];
    })
    .sort((left, right) => left.locator.localeCompare(right.locator));

  return {
    reviews,
    errors: errors.sort(),
    counts: {
      declaration: reviews.filter((review) => review.closure === "declaration").length,
      baselineDebt: reviews.filter((review) => review.closure === "baseline_debt").length,
      reviewedExclusion:
        reviews.filter((review) => review.closure === "reviewed_exclusion").length,
      unmapped: unmapped.length,
    },
  };
}
