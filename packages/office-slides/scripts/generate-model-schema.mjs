/* eslint-disable no-undef, @typescript-eslint/no-unsafe-assignment, @typescript-eslint/no-unsafe-call, @typescript-eslint/no-unsafe-member-access */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { createGenerator } from "ts-json-schema-generator";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "../..");
const outputRoot = resolve(
  repositoryRoot,
  "packages/first-party-apps/presentation/src/generated",
);
const schemaPath = resolve(outputRoot, "native-slide-model.schema.json");
const validatorPath = resolve(outputRoot, "native-slide-model-validator.mjs");
const declarationPath = resolve(outputRoot, "native-slide-model-validator.d.mts");

const schema = createGenerator({
  path: resolve(packageRoot, "src/model/presentation.ts"),
  tsconfig: resolve(packageRoot, "tsconfig.json"),
  type: "SlidesDocument",
  expose: "export",
  topRef: true,
  additionalProperties: true,
  discriminatorType: "json-schema",
  skipTypeCheck: false,
  jsDoc: "extended",
}).createSchema("SlidesDocument");

// ts-json-schema-generator 2.9 merges the nested `placeholder.type` member
// into ElementInit's `type` discriminator when it evaluates the intersection
// used by PlaceholderSpec. Derive the placeholder union from the generator's
// own Element union instead: layout templates are exactly elements without an
// id and with a required PlaceholderRef. This is a schema-generator adapter,
// not a second handwritten model schema.
const elementUnion = schema.definitions?.Element;
const placeholderSpec = schema.definitions?.PlaceholderSpec;
if (!elementUnion?.anyOf || !placeholderSpec) {
  throw new Error("Generated SlidesDocument schema shape changed; cannot derive PlaceholderSpec");
}
const generatedPlaceholderRef = schema.definitions?.PlaceholderRef;
if (!generatedPlaceholderRef?.properties?.type || !generatedPlaceholderRef.properties.index) {
  throw new Error("Generated PlaceholderRef is unavailable");
}
const placeholderRef = structuredClone(generatedPlaceholderRef);
// PlaceholderSpec explicitly permits an omitted index; actual built-in layouts
// rely on that form. Keep the source-derived type vocabulary rather than copying
// its current members into a generator-specific allowlist.
placeholderRef.required = (placeholderRef.required ?? []).filter(key => key !== "index");
schema.definitions.PlaceholderSpec = {
  anyOf: elementUnion.anyOf.map((branch) => {
    const name = branch.$ref?.replace("#/definitions/", "");
    const definition = name ? schema.definitions[name] : undefined;
    if (!definition?.properties) throw new Error("Generated Element branch is not a named object definition");
    const copy = structuredClone(definition);
    copy.properties.placeholder = placeholderRef;
    copy.required = [...(copy.required ?? []).filter((key) => key !== "id"), "placeholder"];
    delete copy.properties.id;
    return copy;
  }),
};

// NotesPanel intentionally persists sparse BlockStyle objects and supplies
// presentation-note defaults while painting. Text elements and table cells
// still use the canonical complete BlockStyle contract.
const blockStyle = schema.definitions?.BlockStyle;
const block = schema.definitions?.Block;
const slide = schema.definitions?.Slide;
if (!blockStyle || !block || !slide?.properties?.notes) {
  throw new Error("Generated SlidesDocument note style schema shape changed");
}
schema.definitions.SlidesNotesBlockStyle = structuredClone(blockStyle);
delete schema.definitions.SlidesNotesBlockStyle.required;
schema.definitions.SlidesNotesBlock = structuredClone(block);
schema.definitions.SlidesNotesBlock.properties.style = { $ref: "#/definitions/SlidesNotesBlockStyle" };
slide.properties.notes.items = { $ref: "#/definitions/SlidesNotesBlock" };

// The model deliberately preserves fields introduced by newer engines. Ajv
// validates every known field without deleting, coercing, or defaulting data.
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  allowUnionTypes: true,
  code: { esm: true, source: true },
});
const validate = ajv.compile(schema);
const validator = standaloneCode(ajv, validate);

const outputs = new Map([
  [schemaPath, `${JSON.stringify(schema, null, 2)}\n`],
  [validatorPath, `// Generated by packages/office-slides/scripts/generate-model-schema.mjs.\n${validator}`],
  [declarationPath, `export type ValidationError = Readonly<{\n  instancePath: string;\n  schemaPath: string;\n  keyword: string;\n  params: Record<string, unknown>;\n  message?: string;\n}>;\ndeclare function validate(value: unknown): boolean;\ndeclare namespace validate { let errors: ValidationError[] | null | undefined; }\nexport { validate };\nexport default validate;\n`],
]);
if (process.argv.includes("--check")) {
  for (const [path, content] of outputs) {
    if (await readFile(path, "utf8") !== content) throw new Error(`Native model schema drift: regenerate ${path}`);
  }
  console.log("Native model schema and standalone validator match their source.");
} else {
  await mkdir(outputRoot, { recursive: true });
  await Promise.all([...outputs].map(([path, content]) => writeFile(path, content, "utf8")));
  console.log(`Generated ${schemaPath}`);
  console.log(`Generated ${validatorPath}`);
}
