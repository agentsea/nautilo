import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { createGenerator } from "ts-json-schema-generator";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "../../..");
const outputRoot = resolve(packageRoot, "src/generated");
const schemaPath = resolve(outputRoot, "native-board-model.schema.json");
const validatorPath = resolve(outputRoot, "native-board-model-validator.mjs");
const declarationPath = resolve(outputRoot, "native-board-model-validator.d.mts");

const schema = createGenerator({
  path: resolve(repositoryRoot, "packages/office-board/src/model/board.ts"),
  tsconfig: resolve(repositoryRoot, "packages/office-board/tsconfig.json"),
  type: "BoardModel",
  expose: "export",
  topRef: true,
  additionalProperties: true,
  discriminatorType: "json-schema",
  skipTypeCheck: false,
  jsDoc: "extended",
}).createSchema("BoardModel");

// model/theme.ts resolveColor passes ThemeColor.value directly to Canvas.
// Document that rendering contract without restricting the native CSS palette.
const literalColor = schema.definitions?.ThemeColor?.anyOf?.find(
  branch => branch.properties?.kind?.const === "srgb",
);
if (!literalColor?.properties?.value) throw new Error("Native literal color schema changed");
literalColor.properties.value.description = "CSS color literal, such as #FFF2A8, rgb(255 242 168), or a CSS named color. Hexadecimal colors include the leading #; bare OOXML hex values render incorrectly.";

// Known fields come from the owned Board/Slides TypeScript model. Unknown
// fields remain available for forward-compatible, lossless container roundtrip.
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  allowUnionTypes: true,
  code: { esm: true, source: true },
});
const validate = ajv.compile(schema);
const validator = standaloneCode(ajv, validate);

const outputs = new Map([
  [schemaPath, `${JSON.stringify(schema, null, 2)}\n`],
  [validatorPath, `// Generated by packages/first-party-apps/board/scripts/generate-board-model-schema.mjs.\n${validator}`],
  [declarationPath, `export type ValidationError = Readonly<{\n  instancePath: string;\n  schemaPath: string;\n  keyword: string;\n  params: Record<string, unknown>;\n  message?: string;\n}>;\ndeclare function validate(value: unknown): boolean;\ndeclare namespace validate { let errors: ValidationError[] | null | undefined; }\nexport { validate };\nexport default validate;\n`],
]);

if (process.argv.includes("--check")) {
  for (const [path, content] of outputs) {
    if (await readFile(path, "utf8") !== content) throw new Error(`Native Board model schema drift: regenerate ${path}`);
  }
  console.log("Native Board model schema and standalone validator match their source.");
} else {
  await mkdir(outputRoot, { recursive: true });
  await Promise.all([...outputs].map(([path, content]) => writeFile(path, content, "utf8")));
  console.log(`Generated ${schemaPath}`);
  console.log(`Generated ${validatorPath}`);
}
