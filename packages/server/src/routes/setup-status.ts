export const SETUP_STATES = [
  "fresh-unclaimed",
  "claimed-needs-auth",
  "server-needs-keys",
  "ready",
] as const;

export type SetupState = (typeof SETUP_STATES)[number];

export type RecommendedSetupSurfaceKind =
  | "electron-onboarding"
  | "workbench-admin"
  | "cli"
  | "ask-admin";

function managedByCloudFromInstance(): boolean {
  return resolveInstance().deploymentMode === "cloud-managed";
}

function shouldExposeClaimInvitePathHint(request: FastifyRequest): boolean {
  return requestAllowsLoopbackTrust(request);
}

type ViewerUserRow = {
  name: string;
  handle: string | null;
};

async function resolveViewerUserRow(userId: string): Promise<ViewerUserRow | null> {
  const directDb = getServerDirectDb();
  const [row] = await directDb
    .select({ name: users.name, handle: users.handle })
    .from(users)
    .where(eq(users.id, userId))
    .limit(1);
  if (!row) return null;
  return { name: row.name, handle: row.handle };
}

/**
 * D219 — replaces the `serverRole === "admin"` gate. `manage_server_settings`
 * is the capability that maps to provider-key / model config
 * (permission-model.md §5); it drives the `server-needs-keys` recommended
 * surface, the claim-invite path hint, and the `reload-env` admin gate.
 */
function buildPublicServerProfile(
  profile: ResolvedServerProfile,
  sessionUserId: string | null | undefined,
): {
  name: string;
  description?: string | null;
  descriptionVisibility?: "public" | "members";
  icon: AvatarRef;
  reviewedAt?: string | null;
} {
  const out: {
    name: string;
    description?: string | null;
    descriptionVisibility?: "public" | "members";
    icon: AvatarRef;
    reviewedAt?: string | null;
  } = {
    name: profile.name,
    icon: profile.icon,
  };
  if (profile.descriptionVisibility === "public" || sessionUserId) {
    out.description = profile.description;
  }
  // D220 Server section — echo the visibility flag to authed viewers so the
  // admin edit form reflects the persisted value instead of defaulting to
  // "public". Omitted for anonymous callers to keep the redacted payload lean.
  if (sessionUserId) {
    out.descriptionVisibility = profile.descriptionVisibility;
    out.reviewedAt = profile.reviewedAt?.toISOString() ?? null;
  }
  return out;
}

let resolveViewerCapabilities: typeof getUserCapabilities = getUserCapabilities;

async function viewerCanManageServerSettings(userId: string): Promise<boolean> {
  try {
    const caps = await resolveViewerCapabilities(userId);
    return caps.includes("manage_server_settings");
  } catch {
    return false;
  }
}

let pinProviderSingleton: PinChallengeProvider | undefined;

function getPinProvider(): PinChallengeProvider {
  pinProviderSingleton ??= new PinChallengeProvider();
  return pinProviderSingleton;
}

